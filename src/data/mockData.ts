export function generateBusSeats(): BusSeat[] {
  const seats: BusSeat[] = [];
  const occupiedSeatNumbers = [3, 4, 7, 8, 11, 14, 15, 19, 23, 27, 31, 32, 35, 40];
  const accessibleSeats = [1, 2];

  let currentNumber = 1;
  for (let row = 1; row <= 12; row++) {
    for (let col = 0; col < 5; col++) {
      if (col === 2) continue; // aisle
      const isOccupied = occupiedSeatNumbers.includes(currentNumber);
      const isAccessible = accessibleSeats.includes(currentNumber);

      seats.push({
        seatNumber: currentNumber,
        row,
        col,
        status: isOccupied ? 'occupied' : isAccessible ? 'accessible' : 'available',
        priceDzd: 850,
      });
      currentNumber++;
    }
  }
  return seats;
}

